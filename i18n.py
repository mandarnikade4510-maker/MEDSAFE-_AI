def current_lang():
    return st.session_state.get("lang", "en")


def t(key, **kw):
    """Text for `key` in the chosen language (falls back to English)."""
    row = TEXT.get(key)
    if row is None:
        return key
    text = row[_IDX.get(current_lang(), 0)] or row[0]
    return text.format(**kw) if kw else text


_REV = {row[0]: k for k, row in TEXT.items() if "{" not in row[0]}


def tx(english):
    """Translate a fixed English message (e.g. one returned by another module); unknown text is returned unchanged."""
    key = _REV.get(english)
    return t(key) if key else english
